    [Fact]
    public void DirectGammaFamilyExactlyMatchesFrozenJqOracleAcrossBroadDomain()
    {
        var bytes = DecompressCorpus();
        var mismatches = new List<string>();

        Assert.Equal(ExpectedCaseCount * RecordSize, bytes.Length);
        Assert.Equal(
            ExpectedRawSha256,
            Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant());

        var negativeZeroTgammaCount = 0;
        for (var index = 0; index < ExpectedCaseCount; index++)
        {
            var record = bytes.AsSpan(index * RecordSize, RecordSize);
            var inputBits = BinaryPrimitives.ReadUInt64LittleEndian(record);
            var expectedLgammaBits =
                BinaryPrimitives.ReadUInt64LittleEndian(record[sizeof(ulong)..]);
            var expectedTgammaBits =
                BinaryPrimitives.ReadUInt64LittleEndian(record[(sizeof(ulong) * 2)..]);
            var input = BitConverter.UInt64BitsToDouble(inputBits);

            RecordBitMismatch(
                mismatches,
                index,
                inputBits,
                "Gamma",
                expectedLgammaBits,
                Gamma(input));
            RecordBitMismatch(
                mismatches,
                index,
                inputBits,
                "Lgamma",
                expectedLgammaBits,
                Lgamma(input));

            var lgammaR = LgammaR(input);
            RecordBitMismatch(
                mismatches,
                index,
                inputBits,
                "LgammaR.Value",
                expectedLgammaBits,
                lgammaR.Value);

            var expectedSign = (expectedTgammaBits & NegativeZeroBits) == 0 ? 1 : -1;
            if (expectedSign != lgammaR.Sign)
            {
                mismatches.Add(
                    $"case {index}, inputBits=0x{inputBits:x16}: " +
                    $"LgammaR.Sign expected={expectedSign} actual={lgammaR.Sign}");
            }

            RecordBitMismatch(
                mismatches,
                index,
                inputBits,
                "Tgamma",
                expectedTgammaBits,
                Tgamma(input));
            if (expectedTgammaBits == NegativeZeroBits)
            {
                negativeZeroTgammaCount++;
            }
        }

        // This guards the five underflow cases that JSON numeric equality would
        // accidentally treat as ordinary +0.
        Assert.Equal(ExpectedNegativeZeroTgammaCount, negativeZeroTgammaCount);
        Assert.True(
            mismatches.Count == 0,
            $"{mismatches.Count} direct gamma-family bit mismatches:{Environment.NewLine}" +
            string.Join(Environment.NewLine, mismatches.Take(20)));
    }

    [Fact]
    public void DirectGammaFamilyPreservesSignedZeroAndPoleSemantics()
    {
        AssertBits(-1, 0, "Gamma(+0)", PositiveInfinityBits, Gamma(0d));
        AssertBits(-1, NegativeZeroBits, "Gamma(-0)", PositiveInfinityBits, Gamma(-0d));
        AssertBits(-1, 0, "Lgamma(+0)", PositiveInfinityBits, Lgamma(0d));
        AssertBits(-1, NegativeZeroBits, "Lgamma(-0)", PositiveInfinityBits, Lgamma(-0d));
        AssertBits(-1, 0, "Tgamma(+0)", PositiveInfinityBits, Tgamma(0d));
        AssertBits(-1, NegativeZeroBits, "Tgamma(-0)", NegativeInfinityBits, Tgamma(-0d));

        Assert.Equal(1, LgammaR(0d).Sign);
        Assert.Equal(-1, LgammaR(-0d).Sign);
        Assert.True(double.IsNaN(Tgamma(-3d)));
        Assert.True(double.IsPositiveInfinity(Lgamma(-3d)));
    }

    [Fact]
    public void DirectTgammaKeepsKnownRegressionOutputsBitExact()
    {
        (double Input, ulong ExpectedBits)[] cases =
        [
            (165.125, 0x7cef2ba815a7f29fUL),
            (6d, 0x405e000000000000UL),
            (171.624, 0x7feff022b3046114UL),
            (-5.069677541587481, 0x3fbb645012d4b98aUL),
            (136.85475495758877, 0x70271509bf8168adUL),
            (-13.808943862263703, 0x3ddd3226a7a3cdfaUL),
        ];

        foreach (var (input, expectedBits) in cases)
        {
            AssertBits(
                -1,
                BitConverter.DoubleToUInt64Bits(input),
                "Tgamma",
                expectedBits,
                Tgamma(input));
        }
    }

    private static TDelegate Bind<TDelegate>(string methodName)
        where TDelegate : Delegate
    {
        var method = CompatType.GetMethod(
            methodName,
            BindingFlags.Public | BindingFlags.Static,
            binder: null,
            types: [typeof(double)],
            modifiers: null);

        return (method ??
            throw new MissingMethodException(CompatType.FullName, methodName))
            .CreateDelegate<TDelegate>();
    }

    private static byte[] DecompressCorpus()
    {
        var compressedBytes = Convert.FromBase64String(ExpectedGzipBase64);
        using var compressed = new MemoryStream(compressedBytes);
        using var gzip = new GZipStream(compressed, CompressionMode.Decompress);
        using var decompressed = new MemoryStream();
        gzip.CopyTo(decompressed);
        return decompressed.ToArray();
    }

    private static void AssertBits(
        int caseIndex,
        ulong inputBits,
        string function,
        ulong expectedBits,
        double actual)
    {
        var actualBits = BitConverter.DoubleToUInt64Bits(actual);
        Assert.True(
            expectedBits == actualBits,
            $"case {caseIndex}, inputBits=0x{inputBits:x16}: {function} " +
            $"expectedBits=0x{expectedBits:x16} actualBits=0x{actualBits:x16}, " +
            $"actual={actual:R}");
    }

    private static void RecordBitMismatch(
        List<string> mismatches,
        int caseIndex,
        ulong inputBits,
        string function,
        ulong expectedBits,
        double actual)
    {
        var actualBits = BitConverter.DoubleToUInt64Bits(actual);
        if (expectedBits == actualBits)
        {
            return;
        }

        mismatches.Add(
            $"case {caseIndex}, inputBits=0x{inputBits:x16}: {function} " +
            $"expectedBits=0x{expectedBits:x16} actualBits=0x{actualBits:x16}, " +
            $"actual={actual:R}");
    }
